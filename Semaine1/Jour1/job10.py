print(f"=== LA PLATEFORME BANK ===")

montant_initial = 5000 # euros
taux_rendement_annuel = 2.0  # pourcentage

gain_annuel_initial = montant_initial * (taux_rendement_annuel / 100)
print(f"=== SIMULATION FINANCIÈRE ===")
print(f"Investissement initial : {montant_initial} €")
print(f"Taux de rendement annuel : {taux_rendement_annuel} %")
print(f"Gain annuel initial : {gain_annuel_initial:.2f} €")
print()

